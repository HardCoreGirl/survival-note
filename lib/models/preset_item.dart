class ExpiryPreset {
  final String id;
  final String defaultNameEn;
  final String defaultNameKo;
  final int months;
  final String bagCategory;
  final String shelterCategory;

  const ExpiryPreset({
    required this.id,
    required this.defaultNameEn,
    required this.defaultNameKo,
    required this.months,
    required this.bagCategory,
    required this.shelterCategory,
  });

  String label(AppLocalizations l10n) {
    switch (id) {
      case 'ramyeon':
        return l10n.presetRamyeon;
      case 'water':
        return l10n.presetWater;
      case 'first_aid':
        return l10n.presetFirstAid;
      case 'canned':
        return l10n.presetCanned;
      case 'freeze_dried':
        return l10n.presetFreezeDried;
      case 'batteries':
        return l10n.presetBatteries;
      default:
        return defaultNameEn;
    }
  }

  String defaultItemName(bool isKo) => isKo ? defaultNameKo : defaultNameEn;

  String categoryForMode(SurvivalMode mode) =>
      mode == SurvivalMode.survivalBag ? bagCategory : shelterCategory;
}

